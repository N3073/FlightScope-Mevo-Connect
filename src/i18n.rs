/// UI languages. The code is what gets saved in the settings.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Language {
    English,
    Finnish,
    Swedish,
    German,
    Italian,
    French,
    Spanish,
    Portuguese,
}

impl Language {
    pub const ALL: [Language; 8] = [
        Language::English,
        Language::Finnish,
        Language::Swedish,
        Language::German,
        Language::Italian,
        Language::French,
        Language::Spanish,
        Language::Portuguese,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Language::English => "en-GB",
            Language::Finnish => "fi",
            Language::Swedish => "sv",
            Language::German => "de",
            Language::Italian => "it",
            Language::French => "fr",
            Language::Spanish => "es",
            Language::Portuguese => "pt",
        }
    }

    /// The language's name in that language, as shown in the selector.
    pub fn native_name(self) -> &'static str {
        match self {
            Language::English => "English (UK)",
            Language::Finnish => "Suomi",
            Language::Swedish => "Svenska",
            Language::German => "Deutsch",
            Language::Italian => "Italiano",
            Language::French => "Français",
            Language::Spanish => "Español",
            Language::Portuguese => "Português",
        }
    }

    /// Matches a saved code or a system locale such as "fi-FI" by its language part.
    pub fn from_code(code: &str) -> Option<Language> {
        let prefix = code.split(['-', '_']).next()?.to_lowercase();
        Language::ALL.into_iter().find(|lang| lang.code().starts_with(&prefix))
    }

    /// The Windows display language if it is supported, otherwise English.
    pub fn from_system() -> Language {
        sys_locale::get_locale()
            .and_then(|locale| Language::from_code(&locale))
            .unwrap_or(Language::English)
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Language::English => &EN,
            Language::Finnish => &FI,
            Language::Swedish => &SV,
            Language::German => &DE,
            Language::Italian => &IT,
            Language::French => &FR,
            Language::Spanish => &ES,
            Language::Portuguese => &PT,
        }
    }
}

